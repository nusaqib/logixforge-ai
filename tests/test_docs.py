    plan = (gen / "TEST_PLAN.md").read_text(encoding="utf-8")
    assert "Output O_Conveyor01_Run" in plan and "Alarm ESTOP_Active" in plan and "HMI screen Overview" in plan
    with open(gen / "ALARMS.csv", newline="", encoding="utf-8") as f:
        assert [r["Name"] for r in csv.DictReader(f)] == ["Conveyor01_Fault", "ESTOP_Active", "SimMode_Active"]
