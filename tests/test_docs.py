def test_ingest_indexes_and_validator_flags_unindexed(tmp_path):
    root = _copy_demo(tmp_path)
    _make_docx(tmp_path / "AL-1234 Vacuum interlocks.docx")
    r = ingest(root, tmp_path / "AL-1234 Vacuum interlocks.docx", title="Vacuum interlocks", doc_no="AL-1234", rev="B", used_for="interlocks")
    assert r["error"] == "" and (root / "docs" / "input" / "AL-1234 Vacuum interlocks.docx").exists()
    ex = root / "docs" / "extracted" / "AL-1234 Vacuum interlocks.md"
    assert ex.exists() and ex.read_text(encoding="utf-8").startswith("<!-- extracted by lf docs ingest")
    rows = read_index(root)
    assert rows[0]["Document no."] == "AL-1234" and rows[0]["Rev"] == "B" and rows[0]["Extracted"].endswith(".md")
    # re-ingest keeps metadata when not given again
    ingest(root, root / "docs" / "input" / "AL-1234 Vacuum interlocks.docx")
    rows = read_index(root)
    assert len(rows) == 1 and rows[0]["Document no."] == "AL-1234"
    # image -> stub + copied next to the .md; unknown format -> indexed but not extracted
    (tmp_path / "pid.png").write_bytes(b"\x89PNG\r\n\x1a\n")
    r = ingest(root, tmp_path / "pid.png")
    assert "Diagram" in r["extracted"].read_text(encoding="utf-8") and (root / "docs" / "extracted" / "pid.png").exists()
    (tmp_path / "old.doc").write_bytes(b"x")
    r = ingest(root, tmp_path / "old.doc")
    assert r["extracted"] is None and "save it as .docx" in r["error"]
    assert read_index(root)[-1]["Extracted"].startswith("NOT EXTRACTED")
    # a file dropped into docs/input without ingest is flagged
    (root / "docs" / "input" / "loose.pdf").write_bytes(b"%PDF")
    codes = {(f.code, f.where) for f in validate(load_project(root))}
    assert ("DOC_INPUT_UNINDEXED", "docs/input/loose.pdf") in codes
    assert ("DOC_INPUT_UNINDEXED", "docs/input/pid.png") not in codes


def test_cli_docs_and_init_layout(tmp_path):
    r = subprocess.run([sys.executable, "-m", "logixforge.cli", "init", str(tmp_path / "p"), "--name", "X_PLC"], capture_output=True, text=True, cwd=ROOT)
    assert r.returncode == 0, r.stderr
    p = tmp_path / "p"
    assert (p / "docs" / "INDEX.md").exists() and (p / "docs" / "input").is_dir() and (p / "docs" / "extracted").is_dir()
    assert (p / ".gitignore").exists() and (p / ".gitattributes").exists() and not (p / ".git").exists()
    r = subprocess.run([sys.executable, "-m", "logixforge.cli", "docs", "build", str(p)], capture_output=True, text=True, cwd=ROOT)
    assert r.returncode == 0 and (p / "docs" / "generated" / "ROUTINES.md").exists(), r.stdout + r.stderr
    r = subprocess.run([sys.executable, "-m", "logixforge.cli", "validate", str(p)], capture_output=True, text=True, cwd=ROOT)
    assert "DOC_SPEC" in r.stdout and "DOC_NONE" not in r.stdout          # placeholder spec flagged, docs generated
    (tmp_path / "notes.md").write_text("# Notes\nStart from HMI only.\n", encoding="utf-8")
    r = subprocess.run([sys.executable, "-m", "logixforge.cli", "docs", "ingest", str(p), str(tmp_path / "notes.md"), "--used-for", "modes"],
                       capture_output=True, text=True, cwd=ROOT)
    assert r.returncode == 0 and "ingested" in r.stdout, r.stdout + r.stderr
    assert "notes.md" in (p / "docs" / "INDEX.md").read_text(encoding="utf-8")
    if shutil.which("pandoc") is None:
        r = subprocess.run([sys.executable, "-m", "logixforge.cli", "docs", "export", str(p), "--to", "docx"], capture_output=True, text=True, cwd=ROOT)
        assert r.returncode != 0 and "pandoc not found" in (r.stdout + r.stderr)


