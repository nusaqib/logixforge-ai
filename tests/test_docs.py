def test_stale_detection_and_validator(tmp_path):
    root = _copy_demo(tmp_path)
    assert is_stale(root) is None
    codes = {f.code for f in validate(load_project(root))}
    assert "DOC_NONE" in codes and "DOC_STALE" not in codes
    generate_docs(load_project(root))
    assert is_stale(root) is False
    (root / "tags" / "controller.json").write_text(
        (root / "tags" / "controller.json").read_text(encoding="utf-8").replace("Heartbeat", "Heart-beat", 1), encoding="utf-8")
    assert is_stale(root) is True
    findings = validate(load_project(root))
    assert any(f.code == "DOC_STALE" and f.level == "warning" for f in findings)
    # editing docs/ or build/ never makes the spec hash change
    h = spec_hash(root)
    (root / "docs" / "SPEC.md").write_text("# changed\n", encoding="utf-8")
    (root / "build").mkdir(exist_ok=True); (root / "build" / "x.L5X").write_text("x", encoding="utf-8")
    assert spec_hash(root) == h


def _make_docx(path: Path):
    doc = ('<?xml version="1.0" encoding="UTF-8"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
           '<w:body><w:p><w:pPr><w:pStyle w:val="Heading1"/></w:pPr><w:r><w:t>Interlocks</w:t></w:r></w:p>'
           '<w:p><w:r><w:t>Trip when </w:t></w:r><w:r><w:t>vacuum &gt; 1e-6</w:t></w:r></w:p>'
           '<w:tbl><w:tr><w:tc><w:p><w:r><w:t>Tag</w:t></w:r></w:p></w:tc><w:tc><w:p><w:r><w:t>Desc</w:t></w:r></w:p></w:tc></w:tr>'
           '<w:tr><w:tc><w:p><w:r><w:t>VG1_Sts</w:t></w:r></w:p></w:tc><w:tc><w:p><w:r><w:t>1 = Ok, 0 = Trip</w:t></w:r></w:p></w:tc></w:tr></w:tbl>'
           '</w:body></w:document>')
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("[Content_Types].xml", '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"/>')
        z.writestr("word/document.xml", doc)


def _make_xlsx(path: Path):
    ss = ('<?xml version="1.0"?><sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" count="3" uniqueCount="3">'
          '<si><t>Tag</t></si><si><t>Module</t></si><si><t>I_PB_Start</t></si></sst>')
    sheet = ('<?xml version="1.0"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>'
             '<row r="1"><c r="A1" t="s"><v>0</v></c><c r="B1" t="s"><v>1</v></c></row>'
             '<row r="2"><c r="A2" t="s"><v>2</v></c><c r="B2"><v>3</v></c></row></sheetData></worksheet>')
    wb = ('<?xml version="1.0"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
          'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="IO" sheetId="1" r:id="rId1"/></sheets></workbook>')
    rels = ('<?xml version="1.0"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="x" Target="worksheets/sheet1.xml"/></Relationships>')
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("xl/sharedStrings.xml", ss); z.writestr("xl/worksheets/sheet1.xml", sheet)
        z.writestr("xl/workbook.xml", wb); z.writestr("xl/_rels/workbook.xml.rels", rels)


