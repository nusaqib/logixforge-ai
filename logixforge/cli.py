"""lf - LogixForge command line.

  lf init <dir> --name CTRL [--processor 1756-L83E] [--rev 33]
  lf validate <project_dir | file.L5X> [--json] [--strict]
  lf build <project_dir> [-o out.L5X]
  lf partial <project_dir> --kind Routine|Program|Tag|DataType|AddOnInstructionDefinition --name X [--program P] -o out.L5X
  lf inspect <file.L5X> [--json] [--routine PROGRAM/ROUTINE]
  lf decompile <file.L5X> -o <project_dir>      # L5X -> editable spec (round-trip / review of uploads)
  lf diff <a.L5X|dir> <b.L5X|dir>
  lf rung check "<rung text>"
  lf online ...  (pycomm3)         lf sdk ...  (Logix Designer SDK)

All subcommands exit non-zero on error so hooks/agents can rely on them.
"""
from __future__ import annotations

import argparse
