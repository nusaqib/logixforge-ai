def _load_any(path: str) -> Project:
    p = Path(path)
    if p.is_dir():
        return load_project(p)
    if p.suffix.lower() == ".l5x":
        return read_l5x(p)
    raise SpecError(f"{path}: expected a project directory or .L5X file")


def _naming_rules(proj_dir: str | None) -> dict:
    """Optional house naming patterns from <project>/naming.json or LOGIXFORGE_NAMING env var."""
    for cand in ([Path(proj_dir) / "naming.json"] if proj_dir else []) + [Path(os.environ.get("LOGIXFORGE_NAMING", ""))]:
        if cand and cand.is_file():
            return json.loads(cand.read_text(encoding="utf-8"))
    return {}


def _print_findings(findings: list[Finding], as_json: bool) -> None:
    if as_json:
        print(json.dumps([f.__dict__ for f in findings], indent=2))
        return
    for f in findings:
        print(f)
    n_err = sum(1 for f in findings if f.level == "error")
    n_warn = sum(1 for f in findings if f.level == "warning")
    print(f"\n{n_err} error(s), {n_warn} warning(s), {len(findings) - n_err - n_warn} info")


