PROFILES_DIR = Path(__file__).resolve().parents[1] / "profiles"


def _apply_profile(root: Path, name: str) -> list[str]:
    """Copy a site profile's naming.json and templates/ into a project. Returns copied paths."""
    import shutil
    pdir = PROFILES_DIR / name
    if not pdir.is_dir():
        sys.exit(f"profile {name!r} not found; available: {sorted(p.name for p in PROFILES_DIR.iterdir() if p.is_dir())}")
    copied = []
    nj = pdir / "naming.json"
    if nj.exists():
        shutil.copy(nj, root / "naming.json")
        copied.append("naming.json")
    tdir = pdir / "templates"
    if tdir.is_dir():
        for src in tdir.rglob("*"):
            if src.is_file() and src.name != "README.md":
                dst = root / src.relative_to(tdir)
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy(src, dst)
                copied.append(str(src.relative_to(tdir)))
    (root / "profile.json").write_text(json.dumps({"profile": name}, indent=2), encoding="utf-8")
    return copied


def cmd_init(a):
    root = Path(a.dir)
    if (root / "controller.json").exists() and not a.force:
        sys.exit(f"{root} already contains controller.json (use --force)")
    sk = {"task": {"name": "MainTask", "kind": "CONTINUOUS", "priority": 10, "watchdog_ms": 500},
          "program": "MainProgram", "main_routine": "MainRoutine", "first_routine": "",
          "controller_description": "{name} - generated by LogixForge"}
    if a.profile:
        skf = PROFILES_DIR / a.profile / "skeleton.json"
        if skf.exists():
            sk.update(json.loads(skf.read_text(encoding="utf-8")))
    prog, main = sk["program"], sk["main_routine"]
    for d in ["datatypes", "tags", f"programs/{prog}/routines", "aois", "modules", "docs/input", "docs/extracted", "tests"]:
        (root / d).mkdir(parents=True, exist_ok=True)
    (root / "controller.json").write_text(json.dumps({
        "name": a.name, "processor_type": a.processor, "major_rev": a.rev, "minor_rev": 11,
        "software_revision": f"{a.rev}.00", "description": sk["controller_description"].format(name=a.name),
        "chassis_size": 10, "slot": 0}, indent=2), encoding="utf-8")
    (root / f"programs/{prog}/program.json").write_text(json.dumps({
        "name": prog, "main_routine": main, "description": "Main program"}, indent=2), encoding="utf-8")
    (root / f"programs/{prog}/tags.json").write_text("[]\n", encoding="utf-8")
    first = sk.get("first_routine") or ""
    body = f"//! Main routine: calls sub-routines in scan order\n// I/O buffering first (inputs snapshot), then control\nJSR({first},0);\n" if first \
        else "//! Main routine: calls sub-routines in scan order\n// Placeholder rung - replace with JSR calls\nNOP();\n"
    (root / f"programs/{prog}/routines/{main}.rll").write_text(body, encoding="utf-8")
    if first:
        (root / f"programs/{prog}/routines/{first}.rll").write_text(
            "//! Input buffering: copy module data to R##S##xx buffer tags (or call DIAG_ AOIs) before control logic\nNOP();\n", encoding="utf-8")
    (root / "tags/controller.json").write_text("[]\n", encoding="utf-8")
    task = dict(sk["task"]); task["programs"] = [prog]
    (root / "tasks.json").write_text(json.dumps([task], indent=2), encoding="utf-8")
    (root / "naming.json").write_text(json.dumps({
        "_comment": "Optional regex per kind: tag, udt, aoi, program, routine, task, member, parameter, local",
        "udt": "^UDT_[A-Za-z0-9_]+$", "aoi": "^AOI_[A-Za-z0-9_]+$"}, indent=2), encoding="utf-8")
    (root / "docs/SPEC.md").write_text(f"# {a.name} - Functional Specification\n\n(Describe the machine/process, I/O, modes, sequences, interlocks, alarms.)\n", encoding="utf-8")
    from .docs.extract import write_index
    write_index(root, [], name=a.name)
    _write_repo_files(root)
    if a.profile:
        copied = _apply_profile(root, a.profile)
        print(f"applied profile {a.profile}: {', '.join(copied) or 'no files'}")
    if a.git:
        import subprocess
        if (root / ".git").exists():
            print("git repository already present")
        else:
            r = subprocess.run(["git", "init", "-q", str(root)], capture_output=True, text=True)
            print("initialised git repository" if r.returncode == 0 else f"git init failed: {r.stderr.strip()}")
    print(f"initialised LogixForge project in {root}")


